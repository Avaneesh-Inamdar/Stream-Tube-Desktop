//! Lightweight UI localization (English / Turkish with YouTube-authentic Turkish terms).

pub fn is_tr() -> bool {
    crate::store::settings_snapshot().app_language.eq_ignore_ascii_case("tr")
}

pub fn tr(en: &'static str, tr: &'static str) -> &'static str {
    if is_tr() { tr } else { en }
}

/// Translates a UI string when Turkish is selected, returning the original string otherwise.
pub fn t(en: &str) -> String {
    if !is_tr() {
        return en.to_string();
    }
    if let Some(v) = lookup_tr(en) {
        return v.to_string();
    }
    en.to_string()
}

